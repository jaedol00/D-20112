import pandas as pd
import plotly.express as px
import streamlit as st

# -----------------------------------------------------------------------------
# 1. 데이터 불러오기 및 캐싱 처리
# -----------------------------------------------------------------------------
# @st.cache_data 데코레이터는 데이터를 한 번 로드한 후 메모리에 저장하여
# 새로고침이나 조작 시 다시 불러오지 않고 재사용하게 해줍니다. (속도 향상)
@st.cache_data
def load_data():
    url = "https://raw.githubusercontent.com/keep-growing-park/data-science/refs/heads/main/dataset/kobis_1year_boxoffice.csv"
    df = pd.read_csv(url)

    # -------------------------------------------------------------------------
    # 2. 날짜 및 데이터 전처리
    # -------------------------------------------------------------------------
    # 결측치(빈 값)가 하나라도 포함된 행을 삭제합니다.
    df = df.dropna()

    # "기준일자" 컬럼을 날짜(datetime) 형식으로 변환합니다.
    df["기준일자"] = pd.to_datetime(df["기준일자"])

    # 데이터를 기준일자 순서대로 오름차순 정렬합니다.
    df = df.sort_values(by="기준일자")

    return df


# 전처리된 데이터를 로드합니다.
df = load_data()

# -----------------------------------------------------------------------------
# 기본 웹앱 레이아웃 설정
# -----------------------------------------------------------------------------
st.set_page_config(page_title="영화 박스오피스 분석 대시보드", layout="wide")
st.title("🎬 영화 박스오피스 관객수 분석")

# -----------------------------------------------------------------------------
# 3. 영화 선택 기능
# -----------------------------------------------------------------------------
# 영화별 최대 누적관객수를 기준으로 내림차순 정렬하여 중복 없는 영화 이름 목록을 추출합니다.
movie_order = (
    df.groupby("영화명")["누적관객수"]
    .max()
    .sort_values(ascending=False)
    .index.tolist()
)

# 사이드바에 영화 선택 드롭다운 목록을 생성합니다.
st.sidebar.header("⚙️ 분석 옵션")
selected_movie = st.sidebar.selectbox("분석할 영화를 선택하세요", movie_order)

# 사용자가 선택한 영화의 데이터만 추출(필터링)합니다.
filtered_df = df[df["영화명"] == selected_movie]

# -----------------------------------------------------------------------------
# 5. 구역 나누기 (탭 구조 활용)
# -----------------------------------------------------------------------------
tab1, tab2 = st.tabs(["📈 일별 관객수 추이", "📊 누적 관객수 추이"])

# -----------------------------------------------------------------------------
# 첫 번째 탭: 선 그래프 (일별 관객수)
# -----------------------------------------------------------------------------
with tab1:
    st.subheader(f"[{selected_movie}] 일별 관객수 변화 그래프")

    # Plotly 선 그래프 생성
    fig_line = px.line(
        filtered_df,
        x="기준일자",
        y="해당일관객수",
        title=f"{selected_movie} - 기준일자별 해당일 관객수 추이",
        markers=True,  # 데이터 포인트에 점 표시
    )

    # 그래프 축 및 레이아웃 커스텀
    fig_line.update_layout(
        xaxis_title="기준일자", yaxis_title="해당일 관객수", hovermode="x unified"
    )

    # 스트림릿 웹 화면에 그래프 출력
    st.plotly_chart(fig_line, use_container_width=True)

    # 하단 설명 영역
    st.info(
        "💡 **이 그래프로 알 수 있는 것:** 영화 개봉 후 날짜별 관객수의 증감 추세와 최고 관객수를 기록한 시점을 파악할 수 있습니다."
    )

# -----------------------------------------------------------------------------
# 두 번째 탭: 영역 차트 (누적 관객수)
# -----------------------------------------------------------------------------
with tab2:
    st.subheader(f"[{selected_movie}] 누적 관객수 변화 그래프")

    # Plotly 영역 차트(Area Chart) 생성
    fig_area = px.area(
        filtered_df,
        x="기준일자",
        y="누적관객수",
        title=f"{selected_movie} - 기준일자별 누적 관객수 추이",
    )

    # 그래프 축 및 레이아웃 커스텀
    fig_area.update_layout(
        xaxis_title="기준일자", yaxis_title="누적 관객수", hovermode="x unified"
    )

    # 스트림릿 웹 화면에 그래프 출력
    st.plotly_chart(fig_area, use_container_width=True)

    # 하단 설명 영역
    st.info(
        "💡 **이 그래프로 알 수 있는 것:** 시간이 지남에 따라 관객수가 누적되는 증가 양상을 한눈에 파악할 수 있으며, 관객수 증가 폭이 둔화되는 흥행 완만 시점을 확인할 수 있습니다."
    )
